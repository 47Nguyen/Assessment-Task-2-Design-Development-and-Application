import os
import sys
import argparse
import logging
from pathlib import Path
import random
import pandas as pd
import numpy as np
import joblib
from PIL import Image
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import tensorflow as tf

# Suppress verbose TF warnings
os.environ['TF_CPP_MIN_LOG_LEVEL'] = '2'
logging.getLogger('tensorflow').setLevel(logging.ERROR)
try:
    import absl.logging
    absl.logging.set_verbosity(absl.logging.ERROR)
except Exception:
    pass

# ---------------------------------------------------------------------------
# 1. Setup & Configuration
# ---------------------------------------------------------------------------
SEED = 42
MODEL_DIR = Path("models")
OUTPUT_DIR = Path("outputs")
CACHE_DIR = Path("cache")
ROOT = Path(".")

# Ensure directories exist
MODEL_DIR.mkdir(parents=True, exist_ok=True)
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
CACHE_DIR.mkdir(parents=True, exist_ok=True)

# Dataset root directory (leave empty to use default A2_FashionDataset/FashionDataset)
folder_path = ""

target_value = "articleType"

# ---------------------------------------------------------------------------
# 2. Self-contained replacement for load_metadata and get_split
# ---------------------------------------------------------------------------
def load_metadata_self_contained(verbose=False):
    """
    Reconstructs metadata and labels split directly from local CSV.
    Guarantees consistent train/validation index mapping.
    """
    base_dir = folder_path if folder_path != "" else "A2_FashionDataset/FashionDataset"
    csv_path = os.path.join(base_dir, "train", "styles_train.csv")
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Missing styles_train.csv at: {csv_path}. Please check folder_path.")
        
    df = pd.read_csv(csv_path, on_bad_lines='skip')
    df = df.iloc[:, :10]  # Drop junk columns
    
    # Filter missing/invalid images
    img_dir = os.path.join(base_dir, "train", "images_train")
    df['img_path'] = df['id'].apply(lambda x: os.path.join(img_dir, f"{x}.jpg"))
    valid_mask = df['img_path'].apply(os.path.exists)
    df = df[valid_mask].reset_index(drop=True)
    
    # Filter out missing labels if any to perfectly match get_split
    df = df.dropna(subset=[target_value]).reset_index(drop=True)
    
    # Split using same random state
    from sklearn.model_selection import train_test_split
    train_df, val_df = train_test_split(df, test_size=0.2, random_state=SEED)
    
    return train_df.reset_index(drop=True), val_df.reset_index(drop=True)

def get_split_self_contained(target_value="articleType", normalised=True, verbose=False):
    """
    Loads dataset splits.
    Replaces get_split from src.data.
    """
    cache_prefix = CACHE_DIR / f"task1_{target_value}"
    X_train_path = f"{cache_prefix}_X_train.npy"
    X_val_path = f"{cache_prefix}_X_val.npy"
    y_train_path = f"{cache_prefix}_y_train.npy"
    y_val_path = f"{cache_prefix}_y_val.npy"
    encoder_path = MODEL_DIR / f"label_encoder_{target_value}.joblib"
    
    if os.path.exists(X_train_path) and os.path.exists(X_val_path) and os.path.exists(y_train_path) and os.path.exists(y_val_path) and os.path.exists(encoder_path):
        X_train = np.load(X_train_path)
        X_val = np.load(X_val_path)
        y_train = np.load(y_train_path)
        y_val = np.load(y_val_path)
        le = joblib.load(encoder_path)
    else:
        if verbose:
            print("Caching dataset splits...")
        base_dir = folder_path if folder_path != "" else "A2_FashionDataset/FashionDataset"
        csv_path = os.path.join(base_dir, "train", "styles_train.csv")
        if not os.path.exists(csv_path):
            raise FileNotFoundError(f"Missing styles_train.csv at: {csv_path}. Please check folder_path.")
            
        df = pd.read_csv(csv_path, on_bad_lines='skip')
        df = df.iloc[:, :10]
        img_dir = os.path.join(base_dir, "train", "images_train")
        df['img_path'] = df['id'].apply(lambda x: os.path.join(img_dir, f"{x}.jpg"))
        valid_mask = df['img_path'].apply(os.path.exists)
        df = df[valid_mask].reset_index(drop=True)
        df = df.dropna(subset=[target_value]).reset_index(drop=True)
        
        from sklearn.preprocessing import LabelEncoder
        le = LabelEncoder()
        df['label'] = le.fit_transform(df[target_value])
        joblib.dump(le, encoder_path)
        
        from sklearn.model_selection import train_test_split
        train_df, val_df = train_test_split(df, test_size=0.2, random_state=SEED)
        
        def load_images_from_df(dataframe):
            images = []
            for path in dataframe['img_path']:
                try:
                    with Image.open(path) as img:
                        img = img.convert('RGB')
                        img = img.resize((60, 80))
                        images.append(np.array(img, dtype=np.uint8))
                except Exception:
                    images.append(np.zeros((80, 60, 3), dtype=np.uint8))
            return np.array(images, dtype=np.uint8)
            
        X_train_raw = load_images_from_df(train_df)
        X_val_raw = load_images_from_df(val_df)
        y_train = train_df['label'].values
        y_val = val_df['label'].values
        
        np.save(X_train_path, X_train_raw)
        np.save(X_val_path, X_val_raw)
        np.save(y_train_path, y_train)
        np.save(y_val_path, y_val)
        
        X_train = X_train_raw
        X_val = X_val_raw
        
    if normalised:
        X_train = X_train.astype(np.float32) / 255.0
        X_val = X_val.astype(np.float32) / 255.0
        
    return X_train, X_val, y_train, y_val, le

